// New interaction-state designs precede runtime wiring. Candidate pixels are
// confined to explicit text/value regions; all other original RGB is retained.
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const sharp=createRequire(import.meta.url)(process.argv[2]??'sharp');
const sourceRoot='art/source/web-v3/results-states-v1',runtimeRoot='art/runtime/web-v3/results-states-v1';
await mkdir(runtimeRoot,{recursive:true});
const layout=JSON.parse(await readFile('art/runtime/web-v3/results-source-v1/layout-v1.json','utf8'));
const sha=async p=>createHash('sha256').update(await readFile(p)).digest('hex');
const jobs={
  landscape:{finalPrimary:[1125,736,245,60],guestSecondary:[538,765,218,60],guestPrimary:[899,760,276,66]},
  portrait:{finalPrimary:[300,1504,350,82],guestSecondary:[330,1358,285,82],guestPrimary:[295,1490,355,85]},
};
const reports=[],runtimeReports=[];
for(const [profile,p]of Object.entries(layout.profiles))for(const state of ['final-round','guest-waiting']){
  const tall=profile==='portrait',view=state==='final-round'?'results':'ranking',s=p[view],g=jobs[profile];
  const source=`art/mockups/web-v3/${tall?'portrait/':''}${view==='results'?'06-results.png':'07-ranking.png'}`;
  const candidate=`${sourceRoot}/${profile}-${state}-candidate-v1.png`;
  const [cw,ch]=p.canvas,metadata=await sharp(candidate).metadata();
  if(metadata.width!==cw||metadata.height!==ch)throw Error('Wrong candidate dimensions '+candidate);
  const before=await sharp(source).removeAlpha().raw().toBuffer(),generated=await sharp(candidate).removeAlpha().raw().toBuffer(),after=Buffer.from(before);
  const allowed=state==='final-round'?[s.roundRoi,g.finalPrimary,...s.rows.flatMap(y=>s.columns.map(x=>[x-56,y-(tall?34:28),112,tall?65:55]))]:[g.guestSecondary,g.guestPrimary];
  for(const[l,t,w,h]of allowed)for(let y=t;y<t+h;y++)for(let x=l;x<l+w;x++){
    const a=Math.max(0,Math.min(1,(x-l)/2,(y-t)/2,(l+w-1-x)/2,(t+h-1-y)/2)),i=(y*cw+x)*3;
    for(let c=0;c<3;c++)after[i+c]=Math.round(after[i+c]*(1-a)+generated[i+c]*a);
  }
  let changed=0,outside=0;
  for(let y=0;y<ch;y++)for(let x=0;x<cw;x++){
    const i=(y*cw+x)*3;if([0,1,2].every(c=>before[i+c]===after[i+c]))continue;changed++;
    if(!allowed.some(([l,t,w,h])=>x>=l&&x<l+w&&y>=t&&y<t+h))outside++;
  }
  if(outside)throw Error('Unrelated source changed '+candidate);
  const design=`art/mockups/web-v3/${tall?'portrait/':''}${state==='final-round'?'34-results-final-round-v1.png':'35-ranking-guest-waiting-v1.png'}`;
  await sharp(after,{raw:{width:cw,height:ch,channels:3}}).png().toFile(design);
  reports.push({profile,state,source,sourceSha256:await sha(source),candidate,candidateSha256:await sha(candidate),allowed,changed,changedOutsideROI:outside,output:design,sha256:await sha(design)});
  // Complete original furniture anatomy; only the canonical label differs.
  for(const kind of state==='final-round'?['primary']:['secondary','primary']){
    const[l,t,w,h]=s[kind],rgba=Buffer.alloc(w*h*4);
    for(let y=0;y<h;y++)for(let x=0;x<w;x++){
      const i=((t+y)*cw+l+x)*3,j=(y*w+x)*4;
      for(let c=0;c<3;c++)rgba[j+c]=after[i+c];
      rgba[j+3]=Math.round(Math.max(0,Math.min(1,x/2,y/2,(w-1-x)/2,(h-1-y)/2))*255);
    }
    const output=`${runtimeRoot}/${profile}-${state}-${kind}-v1.png`;
    await sharp(rgba,{raw:{width:w,height:h,channels:4}}).png().toFile(output);
    runtimeReports.push({profile,state,kind,label:state==='final-round'?'查看最终总榜':kind==='secondary'?'离开房间':'等待房主再开',view,source:design,sourceSha256:await sha(design),rect:s[kind],output,sha256:await sha(output)});
  }
}
const ts=['// Generated by tools/compose-web-result-states-v1.mjs.'];
runtimeReports.forEach((r,i)=>ts.push(`import a${i} from '../../${r.output}';`));
ts.push('export const resultStateActions={');
for(const profile of ['landscape','portrait']){
  ts.push(` ${profile}:{canvas:${JSON.stringify(layout.profiles[profile].canvas)},`);
  for(const[i,r]of runtimeReports.entries())if(r.profile===profile)ts.push(`  '${r.state}-${r.kind}':{src:a${i},rect:${JSON.stringify(r.rect)},label:${JSON.stringify(r.label)},view:${JSON.stringify(r.view)}},`);
  ts.push(' },');
}
ts.push('} as const;');await writeFile('src/web/result-state-actions.generated.ts',ts.join('\n')+'\n');
await writeFile(sourceRoot+'/provenance-v1.json',JSON.stringify({method:'Built-in ImageGen final-round and network-guest terminal state edits. Exact text/value ROIs composed into original selected06/07 sources; all other original RGB invariant. Runtime canonical action tiles preserve original frame anatomy and2px outside feather; live game values never sourced from full-page artwork.',reports,runtimeReports},null,2)+'\n');
console.log({designs:reports.length,runtimePNGs:runtimeReports.length,changedOutsideROI:reports.map(r=>r.changedOutsideROI)});
